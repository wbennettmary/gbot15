"""Typed schemas and safe parsers for AI Placement Optimization (Phase 1).

AI text is never trusted: every provider response goes through
extract_json_object() plus a strict normalizer before it reaches a route.
Phase 2 will extend this module with the full structured contracts
(template analysis, test plans, action plans); Phase 1 ships the
region-suggestion contract used by the existing region editor.
"""

import json
import re

MAX_SUGGESTIONS = 6

SUGGESTION_TEXT_LIMIT = 500

DEFAULT_EXPECTED_LIFT = '+4%'

_OPENROUTER_RATIONALE = 'Generated by OpenRouter.'


def extract_json_object(text_value):
    """Parse the first JSON object found in model text, or return None.

    Ported from the former app.py helper so all AI parsing lives in the
    service layer.
    """
    text_value = (text_value or '').strip()
    if not text_value:
        return None
    try:
        parsed = json.loads(text_value)
        if isinstance(parsed, dict):
            return parsed
    except Exception:
        pass
    match = re.search(r'\{.*\}', text_value, re.DOTALL)
    if not match:
        return None
    try:
        parsed = json.loads(match.group(0))
        return parsed if isinstance(parsed, dict) else None
    except Exception:
        return None


def _clean_suggestion_text(value):
    text = str(value or '').strip()
    if not text:
        return ''
    return text[:SUGGESTION_TEXT_LIMIT]


def normalize_region_suggestions(raw_suggestions, limit=MAX_SUGGESTIONS, rationale_default=_OPENROUTER_RATIONALE):
    """Normalize model output into the {text, rationale, expected_lift} contract.

    Accepts strings or dicts with at least a non-empty text field; anything
    else is ignored. Returns at most `limit` items.
    """
    normalized = []
    for item in (raw_suggestions or [])[:limit]:
        if isinstance(item, str):
            text = _clean_suggestion_text(item)
            if text:
                normalized.append({'text': text, 'rationale': rationale_default, 'expected_lift': DEFAULT_EXPECTED_LIFT})
        elif isinstance(item, dict) and item.get('text'):
            normalized.append({
                'text': _clean_suggestion_text(item.get('text')),
                'rationale': str(item.get('rationale') or rationale_default)[:500],
                'expected_lift': str(item.get('expected_lift') or DEFAULT_EXPECTED_LIFT),
            })
    return normalized


def validate_region_suggestions_payload(parsed):
    """Validate a parsed provider object against the region-suggestion schema.

    Returns the normalized suggestions list (possibly empty), or None when
    the payload is not a JSON object.
    """
    if not isinstance(parsed, dict):
        return None
    return normalize_region_suggestions(parsed.get('suggestions'))


def validate_object_contract(parsed, required_keys=()):
    """Generic Phase 1 validator for future contracts.

    Returns the parsed dict when it is an object containing every required
    key; otherwise None. Callers must treat None as invalid model output.
    """
    if not isinstance(parsed, dict):
        return None
    for key in required_keys:
        if key not in parsed:
            return None
    return parsed


