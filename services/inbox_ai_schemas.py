REQUIRED_HEADER_PLACEHOLDERS = ('[date]', '[to]', '[from]', '[subject]', '[test_id]', '[message_id]')

PLACEHOLDER_PATTERN = re.compile(r'\[[a-z_]{2,32}\]')

MAX_MESSAGE_SUGGESTIONS = 3

MESSAGE_TEXT_LIMIT = 5000


def find_placeholders(text_value):
    """Return the set of [placeholder] tokens present in a draft."""
    if not isinstance(text_value, str) or not text_value:
        return set()
    return set(PLACEHOLDER_PATTERN.findall(text_value.lower()))


def normalize_message_suggestions(raw_suggestions, limit=MAX_MESSAGE_SUGGESTIONS):
    """Normalize model output into [{text, rationale}] message drafts.

    Accepts strings or dicts with a non-empty text field; everything else
    is ignored. Text fields are capped at MESSAGE_TEXT_LIMIT characters.
    """
    normalized = []
    for item in (raw_suggestions or [])[:limit]:
        if isinstance(item, str):
            text = item.strip()[:MESSAGE_TEXT_LIMIT]
            if text:
                normalized.append({'text': text, 'rationale': _OPENROUTER_RATIONALE})
        elif isinstance(item, dict) and str(item.get('text') or '').strip():
            normalized.append({
                'text': str(item.get('text')).strip()[:MESSAGE_TEXT_LIMIT],
                'rationale': str(item.get('rationale') or _OPENROUTER_RATIONALE)[:500],
            })
    return normalized


def placeholder_report(original_text, suggested_text, required=()):
    """Compare placeholder coverage between an original draft and a proposal.

    Returns {ok, missing_required, removed}. ok is False when a suggestion
    would drop placeholders that exist in the original or omit any explicitly
    required placeholders.
    """
    original_tokens = find_placeholders(original_text)
    suggested_tokens = find_placeholders(suggested_text)
    removed = sorted(original_tokens - suggested_tokens)
    missing_required = sorted(token for token in required if token not in suggested_tokens)
    return {
        'ok': not removed and not missing_required,
        'removed': removed,
        'missing_required': missing_required,
    }


_MIME_BOUNDARY_SPLIT = re.compile(r'\n[ \t]*\n')

_HTML_DOCUMENT_SIGNAL = re.compile(r'<\s*(!doctype|html|body)\b', re.IGNORECASE)


def analyze_header_structure(header_text):
    """Deterministic sanity checks for a custom header block.

    A valid header block is RFC-style header lines only: no blank lines
    (which start the body/MIME part) and no embedded HTML document.
    """
    header_text = header_text or ''
    problems = []
    if _MIME_BOUNDARY_SPLIT.search(header_text):
        problems.append('header block must not contain blank lines')
    if _HTML_DOCUMENT_SIGNAL.search(header_text):
        problems.append('header block must not contain HTML document tags')
    has_subject = bool(re.search(r'(?:^|\n)\s*Subject\s*:', header_text, re.IGNORECASE))
    return {'problems': problems, 'has_subject': has_subject}


def local_template_analysis(header_text, body_text, body_mode='html'):
    """Deterministic template analysis used when OpenRouter is unavailable."""
    header = header_text or ''
    body = body_text or ''
    structure = analyze_header_structure(header)
    header_tokens = find_placeholders(header)
    body_tokens = find_placeholders(body)
    missing = [token for token in REQUIRED_HEADER_PLACEHOLDERS if token not in header_tokens]
    risks = list(structure['problems'])
    if missing:
        risks.append(f'missing recommended header placeholders: {", ".join(missing)}')
    if len(body) > 20000:
        risks.append('body is very large; placement tests send it verbatim')
    summary = (
        f"Header: {len(header.splitlines())} lines, subject {'present' if structure['has_subject'] else 'missing'}. "
        f"Body ({body_mode}): {len(body)} chars, {len(body_tokens)} placeholder type(s)."
    )
    return {
        'summary': summary,
        'risks': risks,
        'placeholders': sorted(header_tokens | body_tokens),
        'missing_required_placeholders': missing,
        'has_subject': structure['has_subject'],
    }


