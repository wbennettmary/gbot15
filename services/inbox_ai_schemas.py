QUEUE_RISK_LEVELS = ('low', 'review', 'high')

MAX_QUEUE_ITEMS = 100


def _as_str_list(value, limit=12, item_limit=300):
    if not isinstance(value, list):
        return []
    return [str(item)[:item_limit] for item in value[:limit] if str(item or '').strip()]


def normalize_queue_recommendation(parsed, valid_source_ids):
    """Validate an AI queue review against authoritative source ids.

    Unknown/missing ids are dropped; risk values outside low|review|high
    are coerced to 'review'. Returns None when the payload shape is wrong.
    """
    if not isinstance(parsed, dict):
        return None
    valid_ids = {int(sid) for sid in (valid_source_ids or [])}
    items = []
    for item in (parsed.get('queue_items') or [])[:MAX_QUEUE_ITEMS]:
        if not isinstance(item, dict):
            continue
        try:
            source_id = int(item.get('source_id'))
        except (TypeError, ValueError):
            continue
        if source_id not in valid_ids:
            continue
        risk = str(item.get('risk') or 'review').strip().lower()
        items.append({
            'source_id': source_id,
            'risk': risk if risk in QUEUE_RISK_LEVELS else 'review',
            'reason': str(item.get('reason') or '')[:300],
        })
    cleanup = parsed.get('cleanup') if isinstance(parsed.get('cleanup'), dict) else {}
    delete_candidates = []
    try:
        delete_candidates = sorted({int(sid) for sid in (cleanup.get('delete_candidate_ids') or [])
                                    if int(sid) in valid_ids})
    except (TypeError, ValueError):
        delete_candidates = []
    summary = str(parsed.get('summary') or '').strip()[:1000]
    if not summary:
        return None
    return {
        'summary': summary,
        'queue_items': items,
        'cleanup': {'delete_candidate_ids': delete_candidates},
    }


def local_queue_recommendation(queue_items):
    """Deterministic queue risk scoring used when OpenRouter is unavailable."""
    items = []
    delete_candidates = []
    for item in queue_items[:MAX_QUEUE_ITEMS]:
        risk = 'low'
        reasons = []
        if not item.get('has_html_body') and not item.get('has_text_body'):
            risk = 'high'
            reasons.append('no HTML or plain text body captured')
            delete_candidates.append(item.get('source_id'))
        elif not item.get('has_html_body'):
            risk = 'review'
            reasons.append('plain text body only')
        subject_chars = int(item.get('subject_chars') or 0)
        if not subject_chars:
            risk = 'high'
            reasons.append('subject missing')
            delete_candidates.append(item.get('source_id'))
        elif subject_chars > 90:
            if risk == 'low':
                risk = 'review'
            reasons.append(f'subject is long ({subject_chars} chars)')
        if item.get('already_tested'):
            reasons.append(f"last verdict: {item.get('last_verdict') or 'unknown'}")
            if risk == 'low':
                risk = 'review'
        items.append({'source_id': item.get('source_id'), 'risk': risk,
                      'reason': '; '.join(reasons) or 'no structural issues detected'})
    return {
        'summary': (
            f'Local review of {len(items)} queued template(s): '
            f'{sum(1 for i in items if i["risk"] == "high")} high risk, '
            f'{sum(1 for i in items if i["risk"] == "review")} need review. '
            'Delete candidates are proposals only; deletion stays a manual action.'
        ),
        'queue_items': items,
        'cleanup': {'delete_candidate_ids': sorted({sid for sid in delete_candidates if sid})},
    }


def normalize_allocation_recommendation(parsed, allowed_source_types=('manual', 'list')):
    """Validate an AI workspace allocation recommendation.

    Returns None when required fields are missing or types are invalid.
    """
    if not isinstance(parsed, dict) or not str(parsed.get('summary') or '').strip():
        return None
    per_account_raw = parsed.get('recommended_users_per_account')
    recommended_per_account = None
    if per_account_raw is not None:
        try:
            recommended_per_account = max(1, int(per_account_raw))
        except (TypeError, ValueError):
            recommended_per_account = None
    source_type = str(parsed.get('recommended_source_type') or '').strip().lower()
    if source_type and source_type not in allowed_source_types:
        source_type = ''
    return {
        'summary': str(parsed.get('summary'))[:1000].strip(),
        'recommended_users_per_account': recommended_per_account,
        'recommended_source_type': source_type,
        'warnings': _as_str_list(parsed.get('warnings')),
        'coverage_note': str(parsed.get('coverage_note') or '')[:500],
    }


def local_allocation_recommendation(context):
    """Deterministic allocation advice used when OpenRouter is unavailable."""
    accounts = int(context.get('account_count') or 0)
    users_per_account = context.get('users_per_account')
    target_emails = int(context.get('target_emails') or 0)
    recipients = int(context.get('recipient_count') or 0)
    emails = int(context.get('selected_email_count') or 0)
    warnings = []
    if not accounts:
        warnings.append('No Workspace sources selected yet.')
    if not emails:
        warnings.append('No queued templates selected yet.')
    if target_emails and accounts:
        needed_per_account = -(-target_emails // max(1, accounts * max(1, emails)))
        if users_per_account and users_per_account < needed_per_account:
            warnings.append(
                f'Users per account ({users_per_account}) is below the estimated need '
                f'({needed_per_account}) to reach ~{target_emails} test messages.'
            )
    if users_per_account and recipients and users_per_account * max(1, accounts) < recipients:
        warnings.append('Selected senders are fewer than receiving inboxes; coverage will be partial.')
    return {
        'summary': (
            f'With {accounts} source account(s), users-per-account={users_per_account or "all"}, '
            f'{emails} queued email(s), and {recipients} receiving inbox(es).'
        ),
        'recommended_users_per_account': users_per_account,
        'recommended_source_type': '',
        'warnings': warnings or ['No allocation risks detected with current inputs.'],
        'coverage_note': 'Estimates only; the backend recomputes allocations at run time.',
    }


def normalize_readiness_explanation(parsed):
    """Validate an AI readiness explanation; requires a summary string."""
    if not isinstance(parsed, dict) or not str(parsed.get('summary') or '').strip():
        return None
    return {
        'summary': str(parsed.get('summary'))[:1500].strip(),
        'blockers': _as_str_list(parsed.get('blockers')),
        'next_steps': _as_str_list(parsed.get('next_steps')),
        'coverage_estimate': str(parsed.get('coverage_estimate') or '')[:500],
    }


def local_readiness_explanation(context):
    """Deterministic readiness checklist used when OpenRouter is unavailable."""
    blockers = []
    if not context.get('selected_email_count'):
        blockers.append('Select at least one queued template.')
    has_users = bool(context.get('selected_sender_count')) or bool(context.get('users_per_account'))
    if not context.get('account_count') and not context.get('selected_sender_count'):
        blockers.append('Select a Workspace source (account lookup or list) before running.')
    elif not has_users:
        blockers.append('Retrieve or select Workspace sender users first.')
    if not context.get('recipient_count'):
        blockers.append('Select at least one receiving IMAP inbox.')
    estimate = (
        f"~{context.get('estimated_messages', 0)} message(s) planned "
        f"({context.get('strategy') or 'distributed'} strategy)."
    )
    return {
        'summary': (
            f"Ready check: {len(blockers)} blocker(s). {estimate}"
            if blockers else f"All prerequisites look satisfied. {estimate}"
        ),
        'blockers': blockers,
        'next_steps': [f'Resolve: {blocker}' for blocker in blockers][:6],
        'coverage_estimate': estimate,
    }


def normalize_result_analysis(parsed, valid_senders=None, valid_domains=None):
    """Validate an AI result analysis for one automated test.

    Diagnosis/steps/retry text is capped. Copy-ready lists are intersected
    with the authoritative sender/domain sets observed in DB rows, so the
    model cannot invent addresses. Returns None on a malformed payload.
    """
    if not isinstance(parsed, dict):
        return None
    summary = str(parsed.get('summary') or '').strip()[:1200]
    diagnosis = str(parsed.get('diagnosis') or '').strip()[:2000]
    if not summary and not diagnosis:
        return None
    senders = {str(item).strip().lower() for item in (valid_senders or [])}
    domains = {str(item).strip().lower() for item in (valid_domains or [])}

    def _filtered_list(value, allowed, limit=25):
        items = []
        for item in (value or [])[:limit * 2]:
            text = str(item or '').strip().lower()
            if not text:
                continue
            if allowed and text not in allowed:
                continue
            if text not in items:
                items.append(text)
            if len(items) >= limit:
                break
        return items

    retry_raw = parsed.get('retry_plan') if isinstance(parsed.get('retry_plan'), dict) else {}
    copy_raw = parsed.get('copy_lists') if isinstance(parsed.get('copy_lists'), dict) else {}
    recommended = retry_raw.get('recommended')
    return {
        'summary': summary or diagnosis[:1200],
        'diagnosis': _as_str_list(parsed.get('diagnosis'), limit=8, item_limit=400),
        'next_steps': _as_str_list(parsed.get('next_steps'), limit=8),
        'retry_plan': {
            'recommended': bool(recommended) if recommended is not None else False,
            'steps': _as_str_list(retry_raw.get('steps'), limit=8),
            'warnings': _as_str_list(retry_raw.get('warnings'), limit=6),
        },
        'copy_lists': {
            'inbox_users': _filtered_list(copy_raw.get('inbox_users'), senders),
            'spam_users': _filtered_list(copy_raw.get('spam_users'), senders),
            'inbox_domains': _filtered_list(copy_raw.get('inbox_domains'), domains),
            'spam_domains': _filtered_list(copy_raw.get('spam_domains'), domains),
        },
    }


def local_result_analysis(facts):
    """Deterministic result analysis used when OpenRouter is unavailable."""
    total = int(facts.get('total_messages') or 0)
    inbox_pct = int(facts.get('inbox_pct') or 0)
    spam_pct = int(facts.get('spam_pct') or 0)
    missing_pct = int(facts.get('missing_pct') or 0)
    worst = facts.get('worst_senders') or []
    spam_domains = facts.get('spam_heavy_domains') or []
    errors = facts.get('error_samples') or []
    diagnosis = [
        f"{inbox_pct}% inbox / {spam_pct}% spam / {missing_pct}% unobserved across {total} message(s)."
    ]
    if spam_pct >= 40:
        diagnosis.append('Spam share is high; content and sender reputation both need review.')
    elif inbox_pct >= 80:
        diagnosis.append('Inbox placement is strong for this run.')
    else:
        diagnosis.append('Placement is mixed; compare providers and senders before the next run.')
    if worst:
        diagnosis.append(
            'Highest-spam senders: ' + ', '.join(
                f"{item.get('sender')} ({item.get('spam_pct')}%)" for item in worst[:5]
            ) + '.'
        )
    next_steps = []
    if spam_domains:
        next_steps.append('Review authentication (SPF/DKIM/DMARC) for: ' + ', '.join(
            item.get('domain', '') for item in spam_domains[:5]) + '.')
    if missing_pct >= 20:
        next_steps.append('Re-sync receiving inboxes; many messages are still unobserved.')
    next_steps.append('Copy the healthy sender list below and reuse it as the source set for the next test.')
    retry_recommended = bool(errors) or missing_pct >= 20
    retry_steps = []
    if retry_recommended:
        if errors:
            retry_steps.append('Resolve send errors first: ' + '; '.join(errors[:3]))
        retry_steps.append('Wait for delivery to settle, then press "Sync fresh data" on this test.')
        retry_steps.append('If unobserved messages remain, re-run the same test with the same recipients.')
    warnings = ['Retry is manual: nothing is sent automatically by AI.']
    return {
        'summary': (
            f"Local analysis of {total} message(s): {inbox_pct}% inbox, {spam_pct}% spam, "
            f"{missing_pct}% unobserved."
        ),
        'diagnosis': diagnosis,
        'next_steps': next_steps[:8] or ['No action needed; results look healthy.'],
        'retry_plan': {
            'recommended': retry_recommended,
            'steps': retry_steps,
            'warnings': warnings,
        },
        'copy_lists': {
            'inbox_users': [item.get('sender', '') for item in (facts.get('best_senders') or [])],
            'spam_users': [item.get('sender', '') for item in worst],
            'inbox_domains': [item.get('domain', '') for item in (facts.get('healthy_domains') or [])],
            'spam_domains': [item.get('domain', '') for item in spam_domains],
        },
    }


