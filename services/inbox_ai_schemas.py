def normalize_post_sync_decision(parsed, valid_grey_users=None, grey_update_enabled=False):
    """Validate an AI decision after app-owned sending/syncing/classification.

    The model may recommend whether to change grey-user names and whether to
    retest, but targets are intersected with authoritative grey users from the
    DB classification. This keeps the AI in the judgment layer while the app
    still owns mutation, safety checks, and execution.
    """
    if not isinstance(parsed, dict):
        return None
    valid_by_email = {}
    for item in valid_grey_users or []:
        if not isinstance(item, dict):
            continue
        email = str(item.get('email') or '').strip().lower()
        if email:
            valid_by_email[email] = item
    raw_targets = parsed.get('grey_user_targets') or parsed.get('targets') or []
    targets = []
    seen = set()
    for item in raw_targets[:100]:
        email = str(item.get('email') if isinstance(item, dict) else item or '').strip().lower()
        if email and email in valid_by_email and email not in seen:
            targets.append(valid_by_email[email])
            seen.add(email)
    requested_change = bool(parsed.get('change_grey_names'))
    change_grey_names = bool(grey_update_enabled and requested_change and targets)
    retry_after_changes = bool(change_grey_names and parsed.get('retry_after_changes'))
    if not grey_update_enabled:
        next_action = 'review_only'
    elif change_grey_names:
        next_action = 'change_grey_names'
    elif valid_by_email:
        next_action = 'skip_grey_changes'
    else:
        next_action = 'complete'
    summary = str(parsed.get('summary') or '').strip()[:1200]
    if not summary:
        summary = 'Post-sync analysis completed.'
    rationale = _as_str_list(parsed.get('rationale'), limit=8, item_limit=400)
    safeguards = _as_str_list(parsed.get('safeguards'), limit=8, item_limit=300)
    if not safeguards:
        safeguards = [
            'The app validates every target against observed grey users before changing names.',
            'The app performs Workspace mutations and retests; AI only returns a decision.',
        ]
    return {
        'summary': summary,
        'next_action': next_action,
        'change_grey_names': change_grey_names,
        'retry_after_changes': retry_after_changes,
        'grey_user_targets': targets,
        'rationale': rationale,
        'safeguards': safeguards,
    }


def local_post_sync_decision(facts):
    """Deterministic fallback for the post-sync agent decision."""
    facts = facts or {}
    grey_update_enabled = bool(facts.get('grey_update_enabled'))
    grey_users = [
        item for item in (((facts.get('classification') or {}).get('lists') or {}).get('grey_users') or [])
        if isinstance(item, dict) and item.get('email') and item.get('service_account_id')
    ]
    change = bool(grey_update_enabled and grey_users)
    return {
        'summary': (
            f"Read {facts.get('test_id') or 'the synced test'}: "
            f"{len(grey_users)} grey user(s) are eligible for safe name changes."
            if change else
            f"Read {facts.get('test_id') or 'the synced test'}: no eligible grey-user update will run."
        ),
        'next_action': 'change_grey_names' if change else ('review_only' if not grey_update_enabled else 'complete'),
        'change_grey_names': change,
        'retry_after_changes': change,
        'grey_user_targets': grey_users,
        'rationale': [
            'Grey-user changes are only useful for senders observed in both inbox and spam.',
            'Only grey users with a loaded Workspace service account are eligible.',
        ],
        'safeguards': [
            'Sending and syncing were completed by the app before this decision.',
            'The app validates every target again before mutation.',
            'Retesting is created by the app only after successful name changes.',
        ],
    }
